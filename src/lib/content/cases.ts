export interface CaseResult {
    label: string
    value: string
}

export interface CaseStep {
    title: string
    text?: string
}

export interface CaseLink {
    label: string
    url: string
}

export interface CaseItem {
    id: string
    index?: number // устарело: номер секции считается по порядку на странице
    title: string
    company: string
    period?: string
    problem: string
    // Полный текст решения. Если есть steps — прячется под «Подробнее»
    solution: string
    results: CaseResult[]
    // Одна строка под цифрами: к чему они и за какой период
    context?: string
    // Роль и условия: «1 фронтенд вместо 3», «полставки»
    facts?: string[]
    // Решение по шагам с коротким заголовком у каждого
    steps?: CaseStep[]
    // Сколько было фронтендеров в команде и сколько осталось — схема рядом с цифрами
    team?: { before: number; after: number }
    // Ссылки под заголовком: документация, репозиторий
    links?: CaseLink[]
    // Живой пример вместо визуализации цифр
    demo?: 'mangoscript'
    tags?: string[]
}

