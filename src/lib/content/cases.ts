// Первый результат с такой подписью — вместе с кейсом, где он получен
export const findResult = (cases: CaseItem[], label: string) => {
    for (const caseItem of cases) {
        const result = caseItem.results.find((item) => item.label === label)
        if (result) return { caseItem, result }
    }
    return null
}
